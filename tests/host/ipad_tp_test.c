/* A PTP report in the pad's layout: five 5-byte slots, count, button, scan. */
struct contact {
    int id, tip, x, y;
};

static void ptp_report(uint8_t *r, const struct contact *c, int n, int scan) {
    memset(r, 0, 29);
    for (int i = 0; i < n; i++) {
        uint8_t *s = r + 5 * i;
        s[0] = (uint8_t)(0x01 | (c[i].tip ? 0x02 : 0) | (c[i].id << 4));
        s[1] = c[i].x & 0xff;
        s[2] = c[i].x >> 8;
        s[3] = c[i].y & 0xff;
        s[4] = c[i].y >> 8;
    }
    r[25] = (uint8_t)n;
    r[27] = scan & 0xff;
    r[28] = scan >> 8;
}

static void hex(const char *s, uint8_t *out) {
    for (int i = 0; i < IPAD_TP_REPORT_BYTES; i++) {
        unsigned v;
        sscanf(s + 2 * i, "%2x", &v);
        out[i] = (uint8_t)v;
    }
}

static void expect(struct ipad_tp *tp, const struct contact *c, int n, int scan,
                   const char *want_hex, const char *step) {
    uint8_t ptp[29], got[IPAD_TP_REPORT_BYTES], want[IPAD_TP_REPORT_BYTES];
    ptp_report(ptp, c, n, scan);
    size_t len = ipad_tp_frame(tp, ptp, sizeof(ptp), got);
    hex(want_hex, want);
    if (len != IPAD_TP_REPORT_BYTES || memcmp(got, want, sizeof(want)) != 0) {
        printf("%s: got  ", step);
        for (int i = 0; i < IPAD_TP_REPORT_BYTES; i++) {
            printf("%02X", got[i]);
        }
        printf("\n%s: want %s\n", step, want_hex);
        assert(0);
    }
    printf("%s: matches\n", step);
}

int main(void) {
    struct ipad_tp tp;

    ipad_tp_init(&tp, 1105, 607, 921, 506, 60);
    printf("descriptor %zu bytes, example %zu\n", tp.desc_len, sizeof(example_desc));
    assert(tp.desc_len == sizeof(example_desc));
    assert(memcmp(tp.desc, example_desc, sizeof(example_desc)) == 0);
    puts("descriptor: matches 15.2.1");

    /* 15.2.2, steps 1-5. */
    const struct contact s1[] = {{0, 1, 0x000, 0x0F1}, {1, 1, 0x000, 0x16C}};
    expect(&tp, s1, 2, 0x0000, "030000000300100F0700C0160000000000000000000000000000", "step 1");
    const struct contact s2[] = {{0, 1, 0x114, 0x0F1}, {1, 1, 0x114, 0x16C}};
    expect(&tp, s2, 2, 0x00A7, "03A700000314110F0714C1160000000000000000000000000000", "step 2");
    const struct contact s3[] = {{0, 1, 0x228, 0x0F1}, {1, 1, 0x228, 0x16C}};
    expect(&tp, s3, 2, 0x014E, "034E01000328120F0728C2160000000000000000000000000000", "step 3");
    const struct contact s4[] = {{0, 1, 0x228, 0x0F1}, {1, 0, 0x228, 0x16C}};
    expect(&tp, s4, 2, 0x01F5, "03F501000328120F0628C2160000000000000000000000000000", "step 4");
    const struct contact s5[] = {{0, 1, 0x228, 0x12F}};
    expect(&tp, s5, 1, 0x029C, "039C02000328F212000000000000000000000000000000000000", "step 5");

    /* Feature report 3: Surface Switch in bit 0, Report Rate above it. */
    uint8_t buf[8];
    assert(ipad_tp_get_report(&tp, 3, buf, sizeof(buf)) == 3);
    assert(buf[0] == 3 && buf[1] == (1 | (60 << 1)) && buf[2] == 0);
    uint8_t off[] = {3, 0x00, 0x00};
    ipad_tp_set_report(&tp, 3, off, sizeof(off));
    assert(ipad_tp_get_report(&tp, 3, buf, sizeof(buf)) == 3 && (buf[1] & 1) == 0);

    /* Surface off: buttons still report, contacts do not. */
    uint8_t ptp[29], out[IPAD_TP_REPORT_BYTES];
    ptp_report(ptp, s1, 2, 0);
    ptp[26] = 1;
    ipad_tp_frame(&tp, ptp, sizeof(ptp), out);
    assert(out[3] == 1 && out[4] == 0 && out[8] == 0);
    assert(ipad_tp_get_report(&tp, 0x44, buf, sizeof(buf)) == -1);

    puts("ipad_tp: all checks passed");
    return 0;
}
